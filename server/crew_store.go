const (
	maxCrewMembers       = 16
	crewStateVersion     = 1
	crewInvitePrefix     = "tmcrew1:"
	defaultCrewInviteTTL = 10 * time.Minute

	CrewRoleStandalone = "standalone"
	CrewRoleLead       = "lead"
	CrewRoleMember     = "member"
	CrewRoleDeputy     = "deputy"
)

// CrewNodeIdentity holds the local node's self-signed ECDSA P-256 TLS 1.3
// certificate, private key, and SHA-256 fingerprint.
type CrewNodeIdentity struct {
	ID         string
	Name       string
	CertSha256 string
	CertPEM    string
	TLSCert    tls.Certificate
	X509Cert   *x509.Certificate
	PrivateKey *ecdsa.PrivateKey
	PublicKey  *ecdsa.PublicKey
}

// CrewMember represents a federated Member node registered with the Lead.
// R5.6: Contains only node identity, URL, certificate, role, and per-member
// shared crew HMAC secret — never user passwords, session cookies, paired
// devices, or Web Push VAPID keys.
type CrewMember struct {
	ID              string `json:"id"`
	Name            string `json:"name"`
	URL             string `json:"url"`
	CertSha256      string `json:"certSha256"`
	CertPEM         string `json:"certPem,omitempty"`
	Role            string `json:"role"` // "member" or "deputy"
	SharedSecretHex string `json:"sharedSecretHex,omitempty"`
	JoinedAt        string `json:"joinedAt"`
	LastSeen        string `json:"lastSeen,omitempty"`
	LastTimestampMs int64  `json:"lastTimestampMs,omitempty"`
}

// CrewMemberPublic is the redacted member descriptor safe for status responses
// and Deputy roster replication (R5.6: no secrets or credentials).
type CrewMemberPublic struct {
	ID         string `json:"memberId"`
	Name       string `json:"name"`
	URL        string `json:"url"`
	CertPEM    string `json:"certPem,omitempty"`
	CertSha256 string `json:"certSha256"`
	Role       string `json:"role"`
	JoinedAt   string `json:"joinedAt,omitempty"`
	LastSeen   string `json:"lastSeen,omitempty"`
}

// CrewLeadBinding stores a Member or Deputy node's pinned Lead identity.
type CrewLeadBinding struct {
	CrewID          string `json:"crewId"`
	LeadID          string `json:"leadId"`
	LeadName        string `json:"leadName"`
	LeadURL         string `json:"leadUrl"`
	LeadCertSha256  string `json:"leadCertSha256"`
	LeadCertPEM     string `json:"leadCertPem,omitempty"`
	SharedSecretHex string `json:"sharedSecretHex,omitempty"`
	JoinedAt        string `json:"joinedAt"`
	LastSeen        string `json:"lastSeen,omitempty"`
	LastTimestampMs int64  `json:"lastTimestampMs,omitempty"`
}

// CrewPendingInvite represents a single-use, 10-minute invite generated by a Lead.
type CrewPendingInvite struct {
	InviteID  string `json:"inviteId"`
	Label     string `json:"label,omitempty"`
	SecretHex string `json:"secretHex"`
	CreatedAt string `json:"createdAt"`
	ExpiresAt string `json:"expiresAt"`
}

// CrewInviteToken is the decoded payload inside a `tmcrew1:<base64url>` invite string.
type CrewInviteToken struct {
	CrewID         string `json:"crewId"`
	LeadURL        string `json:"leadUrl"`
	LeadID         string `json:"leadId"`
	LeadName       string `json:"leadName"`
	LeadCertSha256 string `json:"leadCertSha256"`
	LeadCertPEM    string `json:"leadCertPem,omitempty"`
	InviteID       string `json:"inviteId"`
	SecretHex      string `json:"secretHex"`
	Label          string `json:"label,omitempty"`
	ExpiresAt      string `json:"expiresAt"`
}

type crewStateFile struct {
	Version        int                 `json:"version"`
	CrewID         string              `json:"crewId,omitempty"`
	CrewSecretHex  string              `json:"crewSecretHex,omitempty"`
	NodeID         string              `json:"nodeId"`
	NodeName       string              `json:"nodeName"`
	Role           string              `json:"role"`
	AdvertiseURL   string              `json:"advertiseUrl,omitempty"`
	DeputyID       string              `json:"deputyId,omitempty"`
	Members        []CrewMember        `json:"members,omitempty"`
	Roster         []CrewMemberPublic  `json:"roster,omitempty"`
	Lead           *CrewLeadBinding    `json:"lead,omitempty"`
	Warrant        *DeputyWarrant      `json:"warrant,omitempty"`
	PendingInvites []CrewPendingInvite `json:"pendingInvites,omitempty"`
}

// CrewStore manages persistent crew state (`<stateDir>/crew/crew.json`) and
// the local node's ECDSA P-256 certificate (`node-cert.pem`, `node-key.pem`).
type CrewStore struct {
	mu       sync.RWMutex
	dir      string
	filePath string
	identity CrewNodeIdentity
	state    crewStateFile
	lastTs   map[string]int64
}

func NewCrewStore(dir, defaultNodeName string) (*CrewStore, error) {
	if strings.TrimSpace(dir) == "" {
		return nil, errors.New("crew directory is required")
	}
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return nil, fmt.Errorf("create crew dir: %w", err)
	}
	_ = os.Chmod(dir, 0o700)

	if strings.TrimSpace(defaultNodeName) == "" {
		if h, err := os.Hostname(); err == nil && strings.TrimSpace(h) != "" {
			defaultNodeName = strings.TrimSpace(h)
		} else {
			defaultNodeName = "termote-node"
		}
	}

	ident, err := loadOrCreateNodeIdentity(dir, defaultNodeName)
	if err != nil {
		return nil, err
	}

	s := &CrewStore{
		dir:      dir,
		filePath: filepath.Join(dir, "crew.json"),
		identity: ident,
		lastTs:   make(map[string]int64),
	}
	if err := s.load(defaultNodeName); err != nil {
		return nil, err
	}
	return s, nil
}

func loadOrCreateNodeIdentity(dir, nodeName string) (CrewNodeIdentity, error) {
	certPath := filepath.Join(dir, "node-cert.pem")
	keyPath := filepath.Join(dir, "node-key.pem")

	certBytes, certErr := readStateFile(certPath)
	keyBytes, keyErr := readStateFile(keyPath)
	if certErr == nil && keyErr == nil && len(certBytes) > 0 && len(keyBytes) > 0 {
		if ident, err := parseIdentityPEM(certBytes, keyBytes, nodeName); err == nil {
			return ident, nil
		}
	}

	priv, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		return CrewNodeIdentity{}, fmt.Errorf("generate ECDSA P-256 key: %w", err)
	}
	serialLimit := new(big.Int).Lsh(big.NewInt(1), 128)
	serial, err := rand.Int(rand.Reader, serialLimit)
	if err != nil {
		return CrewNodeIdentity{}, fmt.Errorf("generate cert serial: %w", err)
	}
	now := time.Now().UTC()
	tmpl := &x509.Certificate{
		SerialNumber: serial,
		Subject: pkix.Name{
			CommonName:   nodeName,
			Organization: []string{"termote-crew"},
		},
		NotBefore:             now.Add(-1 * time.Hour),
		NotAfter:              now.Add(10 * 365 * 24 * time.Hour),
		KeyUsage:              x509.KeyUsageDigitalSignature | x509.KeyUsageKeyEncipherment,
		ExtKeyUsage:           []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth, x509.ExtKeyUsageClientAuth},
		BasicConstraintsValid: true,
		DNSNames:              []string{"localhost", nodeName},
		IPAddresses:           []net.IP{net.ParseIP("127.0.0.1"), net.ParseIP("::1")},
	}
	der, err := x509.CreateCertificate(rand.Reader, tmpl, tmpl, &priv.PublicKey, priv)
	if err != nil {
		return CrewNodeIdentity{}, fmt.Errorf("create self-signed certificate: %w", err)
	}
	certPEM := pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der})
	pkcs8Bytes, err := x509.MarshalPKCS8PrivateKey(priv)
	if err != nil {
		return CrewNodeIdentity{}, fmt.Errorf("marshal PKCS#8 private key: %w", err)
	}
	keyPEM := pem.EncodeToMemory(&pem.Block{Type: "PRIVATE KEY", Bytes: pkcs8Bytes})

	if err := writeStateFile("crew", dir, "node-cert", certPath, certPEM, false); err != nil {
		return CrewNodeIdentity{}, fmt.Errorf("write node-cert.pem: %w", err)
	}
	if err := writeStateFile("crew", dir, "node-key", keyPath, keyPEM, false); err != nil {
		return CrewNodeIdentity{}, fmt.Errorf("write node-key.pem: %w", err)
	}
	return parseIdentityPEM(certPEM, keyPEM, nodeName)
}

func parseIdentityPEM(certPEM, keyPEM []byte, nodeName string) (CrewNodeIdentity, error) {
	tlsCert, err := tls.X509KeyPair(certPEM, keyPEM)
	if err != nil {
		return CrewNodeIdentity{}, fmt.Errorf("load X509 key pair: %w", err)
	}
	if len(tlsCert.Certificate) == 0 {
		return CrewNodeIdentity{}, errors.New("empty certificate chain")
	}
	x509Cert, err := x509.ParseCertificate(tlsCert.Certificate[0])
	if err != nil {
		return CrewNodeIdentity{}, fmt.Errorf("parse X509 certificate: %w", err)
	}
	priv, ok := tlsCert.PrivateKey.(*ecdsa.PrivateKey)
	if !ok {
		return CrewNodeIdentity{}, errors.New("node private key is not ECDSA")
	}
	pub, ok := x509Cert.PublicKey.(*ecdsa.PublicKey)
	if !ok {
		return CrewNodeIdentity{}, errors.New("node public key is not ECDSA")
	}
	tlsCert.Leaf = x509Cert
	fp := certFingerprintSha256(x509Cert.Raw)
	id := "node-" + fp[:12]
	return CrewNodeIdentity{
		ID:         id,
		Name:       nodeName,
		CertSha256: fp,
		CertPEM:    strings.TrimSpace(string(certPEM)),
		TLSCert:    tlsCert,
		X509Cert:   x509Cert,
		PrivateKey: priv,
		PublicKey:  pub,
	}, nil
}

func (s *CrewStore) load(defaultNodeName string) error {
	s.mu.Lock()
	defer s.mu.Unlock()

	raw, err := readStateFile(s.filePath)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			s.state = crewStateFile{
				Version:  crewStateVersion,
				NodeID:   s.identity.ID,
				NodeName: defaultNodeName,
				Role:     CrewRoleStandalone,
			}
			return s.saveLocked()
		}
		return fmt.Errorf("read crew.json: %w", err)
	}

	var st crewStateFile
	if err := json.Unmarshal(raw, &st); err != nil {
		return fmt.Errorf("decode crew.json: %w", err)
	}
	if st.Version == 0 {
		st.Version = crewStateVersion
	}
	if st.NodeID == "" {
		st.NodeID = s.identity.ID
	} else {
		s.identity.ID = st.NodeID
	}
	if st.NodeName == "" {
		st.NodeName = defaultNodeName
	} else {
		s.identity.Name = st.NodeName
	}
	if st.Role == "" {
		st.Role = CrewRoleStandalone
	}
	for _, m := range st.Members {
		if m.LastTimestampMs > 0 {
			s.lastTs[m.ID] = m.LastTimestampMs
		}
	}
	if st.Lead != nil && st.Lead.LastTimestampMs > 0 {
		s.lastTs[st.Lead.LeadID] = st.Lead.LastTimestampMs
	}
	s.state = st
	return nil
}

func (s *CrewStore) saveLocked() error {
	s.state.Version = crewStateVersion
	raw, err := json.MarshalIndent(s.state, "", "  ")
	if err != nil {
		return fmt.Errorf("encode crew.json: %w", err)
	}
	return writeStateFile("crew", s.dir, "crew", s.filePath, append(raw, '\n'), false)
}

func (s *CrewStore) Identity() CrewNodeIdentity {
	s.mu.RLock()
	defer s.mu.RUnlock()
	return s.identity
}

func (s *CrewStore) Role() string {
	s.mu.RLock()
	defer s.mu.RUnlock()
	if s.state.Role == "" {
		return CrewRoleStandalone
	}
	return s.state.Role
}

func (s *CrewStore) StateSnapshot() crewStateFile {
	s.mu.RLock()
	defer s.mu.RUnlock()
	cp := s.state
	cp.Members = append([]CrewMember(nil), s.state.Members...)
	cp.Roster = append([]CrewMemberPublic(nil), s.state.Roster...)
	cp.PendingInvites = append([]CrewPendingInvite(nil), s.state.PendingInvites...)
	if s.state.Lead != nil {
		leadCopy := *s.state.Lead
		cp.Lead = &leadCopy
	}
	if s.state.Warrant != nil {
		wCopy := *s.state.Warrant
		cp.Warrant = &wCopy
	}
	return cp
}

func (s *CrewStore) SetNodeNameAndURL(name, advertiseURL string) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	if trimmed := strings.TrimSpace(name); trimmed != "" {
		s.state.NodeName = trimmed
		s.identity.Name = trimmed
	}
	if trimmedURL := strings.TrimSpace(advertiseURL); trimmedURL != "" {
		s.state.AdvertiseURL = strings.TrimRight(trimmedURL, "/")
	}
	return s.saveLocked()
}

func crewRandomHex(numBytes int) (string, error) {
	b := make([]byte, numBytes)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return hex.EncodeToString(b), nil
}

func (s *CrewStore) pruneExpiredInvitesLocked(now time.Time) {
	if len(s.state.PendingInvites) == 0 {
		return
	}
	kept := s.state.PendingInvites[:0]
	for _, inv := range s.state.PendingInvites {
		_, exp, err := parseCrewTimestamp(inv.ExpiresAt)
		if err == nil && !now.After(exp) {
			kept = append(kept, inv)
		}
	}
	s.state.PendingInvites = kept
}

// CreateInvite mints a single-use, 10-minute invite token (`tmcrew1:<base64url>`).
func (s *CrewStore) CreateInvite(leadURL, label string, ttl time.Duration, now time.Time) (string, CrewInviteToken, error) {
	s.mu.Lock()
	defer s.mu.Unlock()

	if now.IsZero() {
		now = time.Now().UTC()
	}
	if ttl <= 0 {
		ttl = defaultCrewInviteTTL
	}
	s.pruneExpiredInvitesLocked(now)

	if len(s.state.Members) >= maxCrewMembers {
		return "", CrewInviteToken{}, fmt.Errorf("crew member limit (%d) reached", maxCrewMembers)
	}
	if s.state.CrewID == "" {
		cid, err := crewRandomHex(6)
		if err != nil {
			return "", CrewInviteToken{}, err
		}
		s.state.CrewID = "crew-" + cid
	}
	if s.state.CrewSecretHex == "" {
		csec, err := crewRandomHex(32)
		if err != nil {
			return "", CrewInviteToken{}, err
		}
		s.state.CrewSecretHex = csec
	}
	if s.state.Role == "" || s.state.Role == CrewRoleStandalone {
		s.state.Role = CrewRoleLead
	}
	if trimmedURL := strings.TrimRight(strings.TrimSpace(leadURL), "/"); trimmedURL != "" {
		s.state.AdvertiseURL = trimmedURL
	} else {
		leadURL = s.state.AdvertiseURL
	}
	if leadURL == "" {
		return "", CrewInviteToken{}, errors.New("lead URL is required to generate an invite")
	}

	inviteID, err := crewRandomHex(8)
	if err != nil {
		return "", CrewInviteToken{}, err
	}
	secretHex, err := crewRandomHex(32)
	if err != nil {
		return "", CrewInviteToken{}, err
	}
	createdAt := now.UTC().Format(time.RFC3339)
	expiresAt := now.Add(ttl).UTC().Format(time.RFC3339)

	pending := CrewPendingInvite{
		InviteID:  inviteID,
		Label:     strings.TrimSpace(label),
		SecretHex: secretHex,
		CreatedAt: createdAt,
		ExpiresAt: expiresAt,
	}
	s.state.PendingInvites = append(s.state.PendingInvites, pending)
	if err := s.saveLocked(); err != nil {
		return "", CrewInviteToken{}, err
	}

	tok := CrewInviteToken{
		CrewID:         s.state.CrewID,
		LeadURL:        strings.TrimRight(strings.TrimSpace(leadURL), "/"),
		LeadID:         s.identity.ID,
		LeadName:       s.identity.Name,
		LeadCertSha256: s.identity.CertSha256,
		LeadCertPEM:    s.identity.CertPEM,
		InviteID:       inviteID,
		SecretHex:      secretHex,
		Label:          strings.TrimSpace(label),
		ExpiresAt:      expiresAt,
	}
	rawJSON, err := json.Marshal(tok)
	if err != nil {
		return "", CrewInviteToken{}, err
	}
	encoded := crewInvitePrefix + base64.RawURLEncoding.EncodeToString(rawJSON)
	return encoded, tok, nil
}

func ParseInviteToken(raw string) (*CrewInviteToken, error) {
	trimmed := strings.TrimSpace(raw)
	if !strings.HasPrefix(trimmed, crewInvitePrefix) {
		return nil, errors.New("invite token must start with tmcrew1:")
	}
	b64 := strings.TrimPrefix(trimmed, crewInvitePrefix)
	decoded, err := decodeBase64Flexible(b64)
	if err != nil {
		return nil, fmt.Errorf("decode invite token: %w", err)
	}
	var tok CrewInviteToken
	if err := json.Unmarshal(decoded, &tok); err != nil {
		return nil, fmt.Errorf("parse invite token JSON: %w", err)
	}
	if tok.LeadURL == "" || tok.LeadCertSha256 == "" || tok.InviteID == "" || tok.SecretHex == "" {
		return nil, errors.New("invite token missing required fields")
	}
	return &tok, nil
}

// ConsumeInviteAndRegisterMember validates and consumes a single-use invite token,
// then pins the joining Member in `crew.json` and returns (crewID, crewSecretHex, error).
func (s *CrewStore) ConsumeInviteAndRegisterMember(inviteID, secretHex string, member CrewMember, now time.Time) (string, string, error) {
	s.mu.Lock()
	defer s.mu.Unlock()

	if now.IsZero() {
		now = time.Now().UTC()
	}

	idx := -1
	var matched CrewPendingInvite
	for i, inv := range s.state.PendingInvites {
		if inv.InviteID == inviteID {
			idx = i
			matched = inv
			break
		}
	}
	if idx < 0 {
		return "", "", errors.New("invite not found or already used")
	}
	// Single-use: remove the invite regardless of whether it expired so it can never be retried.
	s.state.PendingInvites = append(s.state.PendingInvites[:idx], s.state.PendingInvites[idx+1:]...)

	_, exp, err := parseCrewTimestamp(matched.ExpiresAt)
	if err != nil || now.After(exp) {
		_ = s.saveLocked()
		return "", "", errors.New("invite token has expired")
	}
	if !constantTimeHexEqual(matched.SecretHex, secretHex) {
		_ = s.saveLocked()
		return "", "", errors.New("invalid invite secret")
	}

	if s.state.CrewID == "" {
		cid, _ := crewRandomHex(6)
		s.state.CrewID = "crew-" + cid
	}
	if s.state.CrewSecretHex == "" {
		csec, _ := crewRandomHex(32)
		s.state.CrewSecretHex = csec
	}
	if member.Name == "" && matched.Label != "" {
		member.Name = matched.Label
	}
	member.SharedSecretHex = s.state.CrewSecretHex
	if err := s.upsertMemberLocked(member, now); err != nil {
		_ = s.saveLocked()
		return "", "", err
	}
	s.state.Role = CrewRoleLead
	if err := s.saveLocked(); err != nil {
		return "", "", err
	}
	return s.state.CrewID, s.state.CrewSecretHex, nil
}

func (s *CrewStore) upsertMemberLocked(member CrewMember, now time.Time) error {
	if now.IsZero() {
		now = time.Now().UTC()
	}
	member.ID = strings.TrimSpace(member.ID)
	member.Name = strings.TrimSpace(member.Name)
	member.URL = strings.TrimRight(strings.TrimSpace(member.URL), "/")
	member.CertSha256 = strings.ToLower(strings.TrimSpace(member.CertSha256))
	if member.ID == "" {
		if len(member.CertSha256) >= 12 {
			member.ID = "node-" + member.CertSha256[:12]
		} else {
			return errors.New("member ID is required")
		}
	}
	if member.Name == "" {
		member.Name = member.ID
	}
	if member.URL == "" {
		return errors.New("member URL is required")
	}
	if len(member.CertSha256) != 64 {
		return errors.New("member certSha256 must be a 64-char SHA-256 hex digest")
	}
	if member.Role == "" {
		member.Role = CrewRoleMember
	}
	if member.JoinedAt == "" {
		member.JoinedAt = now.UTC().Format(time.RFC3339)
	}
	if member.LastSeen == "" {
		member.LastSeen = member.JoinedAt
	}

	existingIdx := -1
	for i, existing := range s.state.Members {
		if existing.ID == member.ID || constantTimeHexEqual(existing.CertSha256, member.CertSha256) {
			existingIdx = i
			break
		}
	}
	if existingIdx < 0 && len(s.state.Members) >= maxCrewMembers {
		return fmt.Errorf("crew member limit (%d) reached", maxCrewMembers)
	}
	if existingIdx >= 0 {
		prev := s.state.Members[existingIdx]
		if member.SharedSecretHex == "" {
			member.SharedSecretHex = prev.SharedSecretHex
		}
		if member.CertPEM == "" {
			member.CertPEM = prev.CertPEM
		}
		if s.state.DeputyID == prev.ID {
			member.Role = CrewRoleDeputy
		}
		s.state.Members[existingIdx] = member
	} else {
		s.state.Members = append(s.state.Members, member)
	}
	if member.LastTimestampMs > s.lastTs[member.ID] {
		s.lastTs[member.ID] = member.LastTimestampMs
	}
	return nil
}

func (s *CrewStore) AddOrUpdateMember(member CrewMember) error {
	s.mu.Lock()
	defer s.mu.Unlock()

	if s.state.CrewID == "" {
		cid, _ := crewRandomHex(6)
		s.state.CrewID = "crew-" + cid
	}
	if s.state.CrewSecretHex == "" {
		if member.SharedSecretHex != "" {
			s.state.CrewSecretHex = member.SharedSecretHex
		} else {
			csec, _ := crewRandomHex(32)
			s.state.CrewSecretHex = csec
		}
	}
	if member.SharedSecretHex == "" {
		member.SharedSecretHex = s.state.CrewSecretHex
	}
	if err := s.upsertMemberLocked(member, time.Now().UTC()); err != nil {
		return err
	}
	if s.state.Role == "" || s.state.Role == CrewRoleStandalone {
		s.state.Role = CrewRoleLead
	}
	return s.saveLocked()
}

func (s *CrewStore) RemoveMember(memberID string) (CrewMember, bool, error) {
	s.mu.Lock()
	defer s.mu.Unlock()

	target := strings.TrimSpace(memberID)
	for i, m := range s.state.Members {
		if m.ID == target || m.Name == target {
			removed := m
			s.state.Members = append(s.state.Members[:i], s.state.Members[i+1:]...)
			delete(s.lastTs, removed.ID)
			if s.state.DeputyID == removed.ID {
				s.state.DeputyID = ""
				s.state.Warrant = nil
			}
			if err := s.saveLocked(); err != nil {
				return CrewMember{}, false, err
			}
			return removed, true, nil
		}
	}
	return CrewMember{}, false, nil
}

func (s *CrewStore) GetMember(memberID string) (CrewMember, bool) {
	s.mu.RLock()
	defer s.mu.RUnlock()

	target := strings.TrimSpace(memberID)
	for _, m := range s.state.Members {
		if m.ID == target {
			return m, true
		}
	}
	return CrewMember{}, false
}

func (s *CrewStore) Members() []CrewMember {
	s.mu.RLock()
	defer s.mu.RUnlock()
	out := make([]CrewMember, len(s.state.Members))
	copy(out, s.state.Members)
	return out
}

func (s *CrewStore) PublicRoster() []CrewMemberPublic {
	s.mu.RLock()
	defer s.mu.RUnlock()
	if len(s.state.Members) > 0 {
		out := make([]CrewMemberPublic, 0, len(s.state.Members))
		for _, m := range s.state.Members {
			role := m.Role
			if s.state.DeputyID != "" && m.ID == s.state.DeputyID {
				role = CrewRoleDeputy
			} else if role == "" {
				role = CrewRoleMember
			}
			out = append(out, CrewMemberPublic{
				ID:         m.ID,
				Name:       m.Name,
				URL:        m.URL,
				CertPEM:    m.CertPEM,
				CertSha256: m.CertSha256,
				Role:       role,
				JoinedAt:   m.JoinedAt,
				LastSeen:   m.LastSeen,
			})
		}
		return out
	}
	out := make([]CrewMemberPublic, len(s.state.Roster))
	copy(out, s.state.Roster)
	return out
}

func (s *CrewStore) SetLeadBinding(binding CrewLeadBinding) error {
	s.mu.Lock()
	defer s.mu.Unlock()

	binding.LeadCertSha256 = strings.ToLower(strings.TrimSpace(binding.LeadCertSha256))
	binding.LeadURL = strings.TrimRight(strings.TrimSpace(binding.LeadURL), "/")
	if binding.JoinedAt == "" {
		binding.JoinedAt = time.Now().UTC().Format(time.RFC3339)
	}
	s.state.CrewID = binding.CrewID
	s.state.Lead = &binding
	if s.state.Role != CrewRoleDeputy {
		s.state.Role = CrewRoleMember
	}
	return s.saveLocked()
}

// DesignateDeputy assigns or clears (`memberID == ""`) the Standby Deputy on the Lead,
// minting a fresh Lead-signed DeputyWarrant.
func (s *CrewStore) DesignateDeputy(memberID string, now time.Time) (*DeputyWarrant, error) {
	s.mu.Lock()
	defer s.mu.Unlock()

	if now.IsZero() {
		now = time.Now().UTC()
	}
	target := strings.TrimSpace(memberID)
	if target == "" || target == "--clear" || target == "none" {
		s.state.DeputyID = ""
		s.state.Warrant = nil
		for i := range s.state.Members {
			s.state.Members[i].Role = CrewRoleMember
		}
		return nil, s.saveLocked()
	}

	var found *CrewMember
	for i := range s.state.Members {
		if s.state.Members[i].ID == target || s.state.Members[i].Name == target {
			s.state.Members[i].Role = CrewRoleDeputy
			found = &s.state.Members[i]
		} else {
			s.state.Members[i].Role = CrewRoleMember
		}
	}
	if found == nil {
		return nil, fmt.Errorf("member %q not found in crew", target)
	}
	if s.state.CrewID == "" {
		cid, _ := crewRandomHex(6)
		s.state.CrewID = "crew-" + cid
	}
	warrant, err := signDeputyWarrant(
		s.identity.PrivateKey,
		s.state.CrewID,
		s.identity.ID,
		found.ID,
		found.CertSha256,
		now,
		now.Add(defaultWarrantHorizon),
	)
	if err != nil {
		return nil, err
	}
	s.state.DeputyID = found.ID
	s.state.Warrant = warrant
	if err := s.saveLocked(); err != nil {
		return nil, err
	}
	return warrant, nil
}

// ApplyWarrantUpdate stores a Lead-signed DeputyWarrant and public roster on a
// Member or Deputy node after verifying the Lead's ECDSA signature.
func (s *CrewStore) ApplyWarrantUpdate(warrant *DeputyWarrant, roster []CrewMemberPublic, now time.Time) error {
	s.mu.Lock()
	defer s.mu.Unlock()

	if s.state.Lead == nil {
		return errors.New("node is not joined to a Lead")
	}
	leadPub, err := s.leadPublicKeyLocked()
	if err != nil {
		return err
	}
	if warrant != nil {
		if err := verifyDeputyWarrant(leadPub, warrant, s.state.CrewID, now); err != nil {
			return err
		}
		s.state.Warrant = warrant
		if warrant.DeputyID == s.identity.ID || constantTimeHexEqual(warrant.DeputyCertSha256, s.identity.CertSha256) {
			s.state.Role = CrewRoleDeputy
			s.state.DeputyID = s.identity.ID
		} else {
			if s.state.Role == CrewRoleDeputy {
				s.state.Role = CrewRoleMember
			}
			s.state.DeputyID = warrant.DeputyID
		}
	} else {
		s.state.Warrant = nil
		s.state.DeputyID = ""
		if s.state.Role == CrewRoleDeputy {
			s.state.Role = CrewRoleMember
		}
	}
	if len(roster) > maxCrewMembers {
		roster = roster[:maxCrewMembers]
	}
	s.state.Roster = append([]CrewMemberPublic(nil), roster...)
	return s.saveLocked()
}

// PromoteDeputy transitions a warranted Standby Deputy into an active controller
// role, populating its pollable `Members` list from the replicated `Roster`.
func (s *CrewStore) PromoteDeputy(now time.Time) error {
	s.mu.Lock()
	defer s.mu.Unlock()

	if s.state.Warrant == nil {
		return errors.New("cannot promote: no Deputy Warrant installed on this node")
	}
	if !constantTimeHexEqual(s.state.Warrant.DeputyCertSha256, s.identity.CertSha256) {
		return errors.New("cannot promote: warrant is not issued to this node's certificate")
	}
	if s.state.Lead != nil {
		if leadPub, err := s.leadPublicKeyLocked(); err == nil {
			if err := verifyDeputyWarrant(leadPub, s.state.Warrant, s.state.CrewID, now); err != nil {
				return fmt.Errorf("cannot promote: %w", err)
			}
		}
	}
	if now.IsZero() {
		now = time.Now().UTC()
	}
	// Populate pollable Members from Roster (excluding self).
	sharedSecret := ""
	if s.state.Lead != nil {
		sharedSecret = s.state.Lead.SharedSecretHex
	}
	for _, r := range s.state.Roster {
		if r.ID == s.identity.ID || constantTimeHexEqual(r.CertSha256, s.identity.CertSha256) {
			continue
		}
		_ = s.upsertMemberLocked(CrewMember{
			ID:              r.ID,
			Name:            r.Name,
			URL:             r.URL,
			CertPEM:         r.CertPEM,
			CertSha256:      r.CertSha256,
			Role:            CrewRoleMember,
			SharedSecretHex: sharedSecret,
			JoinedAt:        r.JoinedAt,
			LastSeen:        r.LastSeen,
		}, now)
	}
	s.state.Role = CrewRoleLead
	s.state.DeputyID = s.identity.ID
	return s.saveLocked()
}

func (s *CrewStore) leadPublicKeyLocked() (*ecdsa.PublicKey, error) {
	if s.state.Lead == nil || strings.TrimSpace(s.state.Lead.LeadCertPEM) == "" {
		return nil, errors.New("pinned lead certificate PEM is unavailable")
	}
	_, fp, pub, err := parseCertPEM(s.state.Lead.LeadCertPEM)
	if err != nil {
		return nil, err
	}
	if !constantTimeHexEqual(fp, s.state.Lead.LeadCertSha256) {
		return nil, errors.New("lead certificate PEM does not match pinned SHA-256 fingerprint")
	}
	return pub, nil
}

// CheckAndAdvanceTimestamp enforces per-sender strictly increasing timestamps
// within the ±5m window so replayed signed requests are rejected.
func (s *CrewStore) CheckAndAdvanceTimestamp(senderID string, tsMs int64, now time.Time) error {
	s.mu.Lock()
	defer s.mu.Unlock()

	key := strings.TrimSpace(senderID)
	if key == "" {
		return errors.New("missing sender ID for replay check")
	}
	if prev, ok := s.lastTs[key]; ok && tsMs <= prev {
		return fmt.Errorf("replayed or out-of-order crew timestamp %d (last=%d)", tsMs, prev)
	}
	s.lastTs[key] = tsMs
	nowStr := now.UTC().Format(time.RFC3339)
	for i := range s.state.Members {
		if s.state.Members[i].ID == key {
			s.state.Members[i].LastTimestampMs = tsMs
			s.state.Members[i].LastSeen = nowStr
		}
	}
	if s.state.Lead != nil && s.state.Lead.LeadID == key {
		s.state.Lead.LastTimestampMs = tsMs
		s.state.Lead.LastSeen = nowStr
	}
	return nil
}

// VerifyControllerCert verifies that rawCertDER belongs to the pinned Lead OR
// to a Deputy holding a valid Lead-signed DeputyWarrant (using constant-time
// SHA-256 digest comparison). Returns the controller's ID, public key, and
// shared HMAC secret.
func (s *CrewStore) VerifyControllerCert(rawCertDER []byte, now time.Time) (senderID string, pub *ecdsa.PublicKey, sharedSecretHex string, err error) {
	s.mu.RLock()
	defer s.mu.RUnlock()

	if len(rawCertDER) == 0 {
		return "", nil, "", errors.New("empty peer certificate")
	}
	cert, err := x509.ParseCertificate(rawCertDER)
	if err != nil {
		return "", nil, "", fmt.Errorf("parse peer certificate: %w", err)
	}
	ecPub, ok := cert.PublicKey.(*ecdsa.PublicKey)
	if !ok {
		return "", nil, "", errors.New("peer certificate does not have an ECDSA public key")
	}
	fp := certFingerprintSha256(rawCertDER)

	// 1. Pinned Lead certificate.
	if s.state.Lead != nil && constantTimeHexEqual(fp, s.state.Lead.LeadCertSha256) {
		return s.state.Lead.LeadID, ecPub, s.state.Lead.SharedSecretHex, nil
	}

	// 2. Warranted Deputy certificate with valid Lead-signed DeputyWarrant.
	if s.state.Warrant != nil && constantTimeHexEqual(fp, s.state.Warrant.DeputyCertSha256) {
		leadPub, lerr := s.leadPublicKeyLocked()
		if lerr != nil {
			return "", nil, "", fmt.Errorf("verify warrant lead key: %w", lerr)
		}
		if werr := verifyDeputyWarrant(leadPub, s.state.Warrant, s.state.CrewID, now); werr != nil {
			return "", nil, "", fmt.Errorf("verify deputy warrant: %w", werr)
		}
		secret := ""
		if s.state.Lead != nil {
			secret = s.state.Lead.SharedSecretHex
		}
		return s.state.Warrant.DeputyID, ecPub, secret, nil
	}

	return "", nil, "", fmt.Errorf("unpinned peer certificate fingerprint %s", fp)
}
